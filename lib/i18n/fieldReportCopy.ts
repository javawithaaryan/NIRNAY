const fieldReportCopy: Record<Language, FieldReportCopy> = { en, hi };

export function useFieldReportCopy(): FieldReportCopy {
  return fieldReportCopy[useLanguage()];
}

export function describeSyncFailure(copy: FieldReportCopy, error: SyncErrorInfo): string {
  return fillTemplate(copy.result.reasons[error.kind], { status: error.httpStatus ?? "—" });
}
